class Command(BaseCommand):
    help = "محور استراتژیک را برای اهداف مالی/مشتری بدون محور تعیین می‌کند."

    def handle(self, *args, **options):
        assigned, not_found = 0, []
        for bu_name, code, theme_name in ASSIGNMENTS:
            try:
                bu = BusinessUnit.objects.get(name__icontains=bu_name)
            except BusinessUnit.DoesNotExist:
                not_found.append(f"کسب‌وکار «{bu_name}» یافت نشد")
                continue
            try:
                obj = StrategicObjective.objects.get(business_unit=bu, code=code)
            except StrategicObjective.DoesNotExist:
                not_found.append(f"هدف {code} در «{bu_name}» یافت نشد")
                continue
            try:
                theme = StrategyTheme.objects.get(business_unit=bu, name=theme_name)
            except StrategyTheme.DoesNotExist:
                not_found.append(f"محور «{theme_name}» در «{bu_name}» یافت نشد")
                continue
            if obj.theme_id != theme.pk:
                obj.theme = theme
                obj.save(update_fields=["theme"])
                assigned += 1

        remaining = StrategicObjective.objects.filter(theme__isnull=True).count()
        self.stdout.write(self.style.SUCCESS(f"محور تعیین شد: {assigned} هدف."))
        self.stdout.write(f"تعداد اهداف باقی‌مانده بدون محور: {remaining}")
        if not_found:
            self.stdout.write(self.style.WARNING("موارد یافت‌نشده:"))
            for msg in not_found:
                self.stdout.write("  - " + msg)
