class Command(BaseCommand):
    help = "اثر/احتمال/عدم‌قطعیت/افق/روند همه‌ی عوامل PESTEL و Porter را با ارزیابی کارشناسی به‌روزرسانی می‌کند."

    def handle(self, *args, **options):
        pestel_by_text = {_norm(f.text): f for f in PestelFactor.objects.all()}
        porter_by_text = {_norm(f.text): f for f in PorterForce.objects.all()}

        updated, missing = 0, []
        for text, impact, prob, uncertainty, horizon, trend in PESTEL_ASSESS:
            f = pestel_by_text.get(_norm(text))
            if not f:
                missing.append(f"PESTEL: {text}")
                continue
            f.impact_level, f.probability = impact, prob
            f.uncertainty, f.horizon, f.trend = uncertainty, horizon, trend
            f.save(update_fields=["impact_level", "probability", "uncertainty", "horizon", "trend"])
            updated += 1

        for text, impact, prob, uncertainty, horizon, trend in PORTER_ASSESS:
            f = porter_by_text.get(_norm(text))
            if not f:
                missing.append(f"Porter: {text}")
                continue
            f.impact_level, f.probability = impact, prob
            f.uncertainty, f.horizon, f.trend = uncertainty, horizon, trend
            f.save(update_fields=["impact_level", "probability", "uncertainty", "horizon", "trend"])
            updated += 1

        self.stdout.write(self.style.SUCCESS(f"به‌روزرسانی شد: {updated} عامل (از {len(PESTEL_ASSESS) + len(PORTER_ASSESS)} مورد ارزیابی‌شده)."))
        if missing:
            self.stdout.write(self.style.WARNING("موارد یافت‌نشده:"))
            for m in missing:
                self.stdout.write("  - " + m)
