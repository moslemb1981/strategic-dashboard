class Command(BaseCommand):
    help = "چشم‌انداز، مأموریت، ارزش‌های سازمانی (با آیکون/رنگ/تعریف/رفتار/نمونه) و خط‌مشی کیفیت واقعی سایپا یدک را ثبت/به‌روزرسانی می‌کند."

    def handle(self, *args, **options):
        OrgIdentity.objects.update_or_create(
            pk=1,
            defaults=dict(
                vision=VISION, mission=MISSION, management_statement=MANAGEMENT_STATEMENT,
                signed_by="رحیم علیشاهی", signed_role="مدیرعامل", signed_date="۱۴۰۵/۰۳/۲۲",
            ),
        )

        # بندهای خط‌مشی را اول می‌سازیم (نه آخر)، چون هر ارزش باید به یکی از این
        # بندها وصل شود؛ بدون حذف‌وبازسازی — با شماره‌ی بند تطبیق داده می‌شود.
        policy_by_number = {}
        for order, (number, text) in enumerate(POLICY_POINTS):
            obj, _ = QualityPolicyPoint.objects.update_or_create(
                number=number, defaults=dict(text=text, order=order),
            )
            policy_by_number[number] = obj

        # به‌روزرسانی امن: تطبیق بر اساس متن ارزش، با نادیده گرفتن نیم‌فاصله (ZWNJ) و فاصله‌ها
        # (چون بعضی رکوردهای قدیمی نیم‌فاصله‌ی متفاوتی داشتند و مقایسه‌ی دقیق باعث ساخت
        # رکورد تکراری می‌شد). متن اصلی موجود در دیتابیس دست‌نخورده می‌ماند (اگر مدیر سیستم
        # قبلاً ویرایشش کرده)، فقط فیلدهای جدید (آیکون/رنگ/تعریف/رفتار/نمونه/بند مرتبط)
        # به‌روزرسانی می‌شود.
        #
        # نگاشت هر ارزش پیرامونی به یک بند خط‌مشی: بر اساس ترتیب است (ارزش ۱‌ام ← بند ۱،
        # ارزش ۲‌ام ← بند ۲ و... تا ارزش ۷‌ام ← بند ۷) — این ترتیب دقیقاً همون ترتیب چرخشی
        # روی چرخ است. «مشتری‌مداری» در مرکز به‌عمد به هیچ بندی وصل نمی‌شود؛ چون خودش
        # هسته‌ی مرکزی همه‌ی ارزش‌هاست، نه یک بند خاص — با کلیک روی مرکز، فقط خودش
        # (بدون توضیح اضافه) نمایش داده می‌شود. این نگاشت پیش‌فرض شروع است — مدیر سیستم
        # می‌تواند از همان فرم ویرایش هر ارزش، بند مرتبط را با یک انتخاب ساده عوض کند.
        def _norm(s):
            return (s or "").replace("\u200c", "").replace(" ", "").strip()

        existing_by_norm = {_norm(v.text): v for v in OrgValue.objects.all()}

        outer_index = 0
        for order, v in enumerate(VALUES):
            key = _norm(v["text"])
            obj = existing_by_norm.get(key)

            if v["is_center"]:
                policy = None
            else:
                outer_index += 1
                policy = policy_by_number.get(outer_index)

            extra = dict(
                is_center=v["is_center"], order=order,
                icon=v["icon"], color=v["color"],
                definition=v["definition"],
                expected_behaviors=v["expected_behaviors"],
                examples=v["examples"],
                related_policy=policy,
            )
            if obj:
                for field, value in extra.items():
                    setattr(obj, field, value)
                obj.save()
            else:
                OrgValue.objects.create(text=v["text"], **extra)

        self.stdout.write(self.style.SUCCESS(
            f"ثبت شد: چشم‌انداز/مأموریت، {len(VALUES)} ارزش سازمانی (با جزئیات کامل و اتصال به بند خط‌مشی)، "
            f"{len(POLICY_POINTS)} بند خط‌مشی کیفیت."
        ))
