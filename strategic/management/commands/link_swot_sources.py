class Command(BaseCommand):
    help = "موارد SWOT را بر اساس تحلیل محتوایی به منبع اصلی‌شان (PESTEL/Porter/7S/زنجیره ارزش) وصل می‌کند."

    def handle(self, *args, **options):
        linked, skipped = 0, 0
        for pks, source_type, source_key in LINKS:
            for pk in pks:
                try:
                    si = SWOTItem.objects.get(pk=pk)
                except SWOTItem.DoesNotExist:
                    skipped += 1
                    continue
                if source_type == 'pestel':
                    si.source_pestel_id = source_key
                elif source_type == 'porter':
                    si.source_porter_id = source_key
                elif source_type == '7s':
                    si.source_7s_id = source_key
                elif source_type == 'vc':
                    si.source_value_chain_id = source_key
                si.save()
                linked += 1

        self.stdout.write(self.style.SUCCESS(f"ثبت شد: {linked} مورد SWOT به منبع اصلی وصل شد."))
        if skipped:
            self.stdout.write(self.style.WARNING(f"{skipped} مورد (شناسه‌ی نامعتبر) رد شد."))
