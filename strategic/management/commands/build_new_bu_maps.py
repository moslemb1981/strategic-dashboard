PERSP = {"F": "financial", "C": "customer", "P": "process", "L": "learning"}


class Command(BaseCommand):
    help = "ساخت نقشه استراتژیک ۳ کسب‌وکار جدید (پیش‌فرض: فقط گزارش)"

    def add_arguments(self, parser):
        parser.add_argument("--apply", action="store_true")
        parser.add_argument("--force", action="store_true", help="نقشه موجود همان کسب‌وکار را پس از پشتیبان جایگزین کن")

    def handle(self, *a, **o):
        todo = []
        for key, (arch, cards) in MAPS.items():
            bu = BusinessUnit.objects.filter(name__contains=key).first()
            if not bu:
                raise CommandError(f"کسب‌وکار «{key}» پیدا نشد.")
            codes = [c[0] for c in cards]
            assert len(codes) == len(set(codes))
            for c in cards:
                assert all(t in codes for t in c[4]), c
            have = StrategicObjective.objects.filter(business_unit=bu).count()
            tows = {(t.category, t.order): t for t in TOWSStrategy.objects.filter(business_unit=bu)}
            miss = [c[3] for c in cards if c[3] and (c[3][:2], int(c[3][2:])) not in tows]
            self.stdout.write(f"{bu.name}: {len(cards)} کارت، {sum(len(c[4]) for c in cards)} پیکان، "
                              f"موجود فعلی: {have}، TOWS یافت‌نشده: {miss or 'ندارد'}")
            if have and not o["force"]:
                self.stdout.write("  ← نقشه دارد؛ بدون --force رد می‌شود.")
                continue
            todo.append((bu, arch, cards, tows, have))
        if not o["apply"]:
            self.stdout.write("\nحالت گزارش: چیزی تغییر نکرد. برای اعمال، --apply را اضافه کنید.")
            return
        for bu, arch, cards, tows, have in todo:
            if have:
                path, _ = save_snapshot(bu, prefix="new_bu_map")
                self.stdout.write(f"پشتیبان: {path}")
            with transaction.atomic():
                StrategicObjective.objects.filter(business_unit=bu).delete()
                themes = {}
                for i, n in enumerate(THEMES):
                    t = StrategyTheme.objects.filter(business_unit=bu, name=n).first() or StrategyTheme(business_unit=bu, name=n)
                    t.order = i
                    t.save()
                    themes[n] = t
                objs, per = {}, {}
                for code, th, title, tw, feeds in cards:
                    p = PERSP[code[0]]
                    per[p] = per.get(p, 0) + 1
                    t = tows.get((tw[:2], int(tw[2:]))) if tw else None
                    objs[code] = StrategicObjective.objects.create(
                        code=code, perspective=p, theme=themes[th], title=title, status="on",
                        order=per[p], business_unit=bu, source_tows=t)
                for code, th, title, tw, feeds in cards:
                    objs[code].feeds_into.set([objs[x] for x in feeds])
                bu.archetype = arch
                bu.save()
            self.stdout.write(self.style.SUCCESS(f"{bu.name}: نقشه ساخته شد ({len(cards)} کارت)."))
