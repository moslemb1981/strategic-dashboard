class Command(BaseCommand):
    help = "به‌روزرسانی متن ۹ راهبرد TOWS «آپشن» طبق نسخه‌ی نهایی SWOT (بدون حذف/ساخت رکورد جدید)."

    def handle(self, *args, **options):
        updated, missing = 0, []
        for pk, new_text in UPDATES.items():
            try:
                obj = TOWSStrategy.objects.get(pk=pk)
            except TOWSStrategy.DoesNotExist:
                missing.append(pk)
                continue
            obj.text = new_text
            obj.save()
            updated += 1

        self.stdout.write(self.style.SUCCESS(f"{updated} راهبرد TOWS «آپشن» به‌روزرسانی شد."))
        if missing:
            self.stdout.write(self.style.ERROR(
                f"⚠️ شناسه‌های زیر پیدا نشدن (پرش شد، احتمالاً دیتابیس فرق داره): {missing}"
            ))
