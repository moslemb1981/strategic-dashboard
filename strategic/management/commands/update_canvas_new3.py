class Command(BaseCommand):
    help = "بازنویسی بوم ۳ کسب‌وکار جدید (پیش‌فرض: فقط گزارش)"

    def add_arguments(self, p):
        p.add_argument("--apply", action="store_true")

    def handle(self, *a, **o):
        plan = []
        for key, blocks in DATA.items():
            bus = [b for b in BusinessUnit.objects.all() if key in b.name]
            if len(bus) != 1:
                raise CommandError(f"«{key}»: {len(bus)} کسب‌وکار منطبق پیدا شد.")
            bu = bus[0]
            for items in blocks.values():
                assert all(len(t) <= 300 for t in items)
            have = BusinessCanvasItem.objects.filter(business_unit=bu).count()
            self.stdout.write(f"■ {bu.name}: فعلی {have} مورد ← جدید {sum(len(v) for v in blocks.values())} مورد")
            plan.append((bu, blocks))
        if not o["apply"]:
            self.stdout.write(self.style.WARNING("حالت گزارش: چیزی تغییر نکرد. برای اعمال، --apply را اضافه کنید."))
            return
        os.makedirs("backups", exist_ok=True)
        path = f"backups/canvas_new3_{datetime.datetime.now():%Y%m%d_%H%M%S}.json"
        with open(path, "w", encoding="utf-8") as f:
            json.dump(list(BusinessCanvasItem.objects.filter(business_unit__in=[p[0] for p in plan]).values()),
                      f, ensure_ascii=False, default=str)
        with transaction.atomic():
            for bu, blocks in plan:
                BusinessCanvasItem.objects.filter(business_unit=bu).delete()
                for block, items in blocks.items():
                    for order, text in enumerate(items):
                        BusinessCanvasItem.objects.create(
                            business_unit=bu, block=block, text=text, note=NOTE, status="approved", order=order)
        self.stdout.write(self.style.SUCCESS(f"انجام شد. پشتیبان: {path}"))
