class Command(BaseCommand):
    help = "به‌روزرسانی متن SWOT/TOWS «بازرگانی قطعات» طبق نسخه‌ی نهایی (بدون حذف/ساخت رکورد جدید)."

    def handle(self, *args, **options):
        updated_swot, missing_swot = 0, []
        for pk, new_text in SWOT_UPDATES.items():
            try:
                obj = SWOTItem.objects.get(pk=pk)
            except SWOTItem.DoesNotExist:
                missing_swot.append(pk)
                continue
            obj.text = new_text
            obj.save()
            updated_swot += 1

        updated_tows, missing_tows = 0, []
        for pk, new_text in TOWS_UPDATES.items():
            try:
                obj = TOWSStrategy.objects.get(pk=pk)
            except TOWSStrategy.DoesNotExist:
                missing_tows.append(pk)
                continue
            obj.text = new_text
            obj.save()
            updated_tows += 1

        self.stdout.write(self.style.SUCCESS(
            f"{updated_swot} آیتم SWOT و {updated_tows} راهبرد TOWS «بازرگانی قطعات» به‌روزرسانی شد."
        ))
        if missing_swot or missing_tows:
            self.stdout.write(self.style.ERROR(
                f"⚠️ شناسه‌های پیدانشده (دیتابیس فرق داره؟) — SWOT: {missing_swot} | TOWS: {missing_tows}"
            ))
