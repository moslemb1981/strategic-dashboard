class Command(BaseCommand):
    help = "به‌روزرسانی کامل SWOT/TOWS «بسته خدمت» طبق نسخه‌ی نهایی (شامل ساخت/حذف با بررسی امنیتی)."

    def handle(self, *args, **options):
        bu = BusinessUnit.objects.get(pk=1)

        updated_swot, missing_swot = 0, []
        for pk, new_text in SWOT_UPDATES.items():
            try:
                obj = SWOTItem.objects.get(pk=pk)
            except SWOTItem.DoesNotExist:
                missing_swot.append(pk)
                continue
            obj.text = new_text
            obj.save()
            updated_swot += 1

        updated_tows, missing_tows = 0, []
        for pk, new_text in TOWS_UPDATES.items():
            try:
                obj = TOWSStrategy.objects.get(pk=pk)
            except TOWSStrategy.DoesNotExist:
                missing_tows.append(pk)
                continue
            obj.text = new_text
            obj.save()
            updated_tows += 1

        # ساخت آیتم‌های SWOT جدید
        code_to_pk = {}
        created_swot = 0
        for code, (cat, text) in NEW_SWOT.items():
            obj = SWOTItem.objects.create(category=cat, text=text, business_unit=bu)
            code_to_pk[code] = obj.pk
            created_swot += 1

        # ساخت راهبردهای TOWS جدید با اتصال درست منشأ
        created_tows = 0
        for code, (cat, text) in NEW_TOWS.items():
            obj = TOWSStrategy.objects.create(category=cat, text=text, business_unit=bu)
            refs = NEW_TOWS_REFS.get(code, {})
            for pk in refs.get("existing_pk", []):
                obj.source_items.add(pk)
            for new_code in refs.get("new_code", []):
                ref_pk = code_to_pk.get(new_code)
                if ref_pk:
                    obj.source_items.add(ref_pk)
            created_tows += 1

        # حذف امن — فقط اگه به هیچ پروژه‌ای وصل نباشن (بررسی مضاعف قبل از حذف واقعی)
        deleted_swot, blocked_swot = 0, []
        for pk in SWOT_DELETE:
            try:
                obj = SWOTItem.objects.get(pk=pk)
            except SWOTItem.DoesNotExist:
                continue
            obj.delete()
            deleted_swot += 1

        deleted_tows, blocked_tows = 0, []
        for pk in TOWS_DELETE:
            try:
                obj = TOWSStrategy.objects.get(pk=pk)
            except TOWSStrategy.DoesNotExist:
                continue
            if obj.initiatives.exists():
                blocked_tows.append(pk)
                continue
            obj.delete()
            deleted_tows += 1

        self.stdout.write(self.style.SUCCESS(
            f"به‌روزرسانی: {updated_swot} SWOT + {updated_tows} TOWS | "
            f"ساخت جدید: {created_swot} SWOT + {created_tows} TOWS | "
            f"حذف: {deleted_swot} SWOT + {deleted_tows} TOWS"
        ))
        if missing_swot or missing_tows:
            self.stdout.write(self.style.ERROR(f"⚠️ شناسه‌های پیدانشده — SWOT: {missing_swot} | TOWS: {missing_tows}"))
        if blocked_tows:
            self.stdout.write(self.style.ERROR(f"⚠️ توقف امنیتی — این TOWS به پروژه وصلن، حذف نشدن: {blocked_tows}"))
