class Command(BaseCommand):
    help = "اهداف استراتژیک آپشن را به پروژه‌های واقعاً مرتبط وصل می‌کند."

    def handle(self, *args, **options):
        bu = BusinessUnit.objects.filter(name__icontains="آپشن").first()
        if not bu:
            self.stdout.write(self.style.ERROR("کسب‌وکار «آپشن» یافت نشد."))
            return

        obj_by_code = {o.code: o for o in StrategicObjective.objects.filter(business_unit=bu)}
        init_by_code = {i.code: i for i in Initiative.objects.all()}

        linked, not_found = 0, []
        for obj_code, init_code in PAIRS:
            obj = obj_by_code.get(obj_code)
            if not obj:
                not_found.append(f"هدف {obj_code} (آپشن) یافت نشد")
                continue
            init = init_by_code.get(init_code)
            if not init:
                not_found.append(f"پروژه {init_code} یافت نشد")
                continue
            init.objectives.add(obj)
            linked += 1

        self.stdout.write(self.style.SUCCESS(f"ثبت شد: {linked} ارتباط هدف-پروژه (آپشن)."))
        if not_found:
            self.stdout.write(self.style.WARNING("موارد یافت‌نشده:"))
            for msg in not_found:
                self.stdout.write("  - " + msg)
