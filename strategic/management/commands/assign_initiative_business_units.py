class Command(BaseCommand):
    help = "کسب‌وکار هر پروژه را طبق تخصیص نهایی (خودکار + اصلاح‌شده‌ی کاربر) تنظیم می‌کند."

    def handle(self, *args, **options):
        bu_by_pk = {bu.pk: bu for bu in BusinessUnit.objects.all()}
        updated, not_found = 0, []
        for key, bu_pk in PAIRS:
            bu = bu_by_pk.get(bu_pk)
            if not bu:
                not_found.append(f"کسب‌وکار با شناسه {bu_pk} یافت نشد")
                continue
            qs = Initiative.objects.filter(code=key)
            if not qs.exists():
                qs = Initiative.objects.filter(title=key, code="")
            if not qs.exists():
                not_found.append(f"پروژه «{key}» یافت نشد")
                continue
            qs.update(business_unit=bu)
            updated += 1

        self.stdout.write(self.style.SUCCESS(f"به‌روزرسانی شد: {updated} پروژه."))
        if not_found:
            self.stdout.write(self.style.WARNING("موارد یافت‌نشده:"))
            for msg in not_found:
                self.stdout.write("  - " + msg)
