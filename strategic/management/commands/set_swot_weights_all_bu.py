class Command(BaseCommand):
    help = "وزن اهمیت (۱ تا ۵) همه‌ی موارد SWOT هر ۵ کسب‌وکار را بر اساس تحلیل محتوا تنظیم می‌کند."

    def handle(self, *args, **options):
        updated, missing = 0, 0
        for bu_name, cats in WEIGHTS.items():
            bu = BusinessUnit.objects.filter(name=bu_name).first()
            if not bu:
                self.stdout.write(self.style.ERROR(f"کسب‌وکار «{bu_name}» پیدا نشد؛ رد شد."))
                continue
            for category, items in cats.items():
                for text, weight in items:
                    n = SWOTItem.objects.filter(business_unit=bu, category=category, text=text).update(weight=weight)
                    if n:
                        updated += n
                    else:
                        missing += 1
                        self.stdout.write(self.style.WARNING(
                            f"پیدا نشد ({bu_name} / {category}): {text[:40]}..."
                        ))
        self.stdout.write(self.style.SUCCESS(f"پایان: {updated} مورد به‌روزرسانی شد، {missing} مورد پیدا نشد."))
