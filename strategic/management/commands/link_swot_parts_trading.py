CODE_REF_PAT = re.compile(r"\b([SWOT])(\d{1,2})\b")


class Command(BaseCommand):
    help = "راهبردهای TOWS موجودِ «بازرگانی قطعات» را به موارد SWOT واقعی وصل می‌کند (بدون حذف/بازسازی)."

    def handle(self, *args, **options):
        bu = BusinessUnit.objects.filter(name=BU_NAME).first()
        if not bu:
            self.stdout.write(self.style.ERROR(f"کسب‌وکار «{BU_NAME}» پیدا نشد."))
            return

        code_map = {}
        for prefix, texts in [("S", STRENGTHS), ("W", WEAKNESSES), ("O", OPPORTUNITIES), ("T", THREATS)]:
            django_cat = prefix.lower()
            for order, text in enumerate(texts, start=1):
                item = SWOTItem.objects.filter(business_unit=bu, category=django_cat, text=text).first()
                if item:
                    code_map[f"{prefix}{order}"] = item
                else:
                    self.stdout.write(self.style.WARNING(f"مورد پیدا نشد (رد شد): {prefix}{order} — {text[:40]}..."))

        linked, skipped = 0, 0
        for strat in TOWSStrategy.objects.filter(business_unit=bu):
            refs = []
            for m in CODE_REF_PAT.finditer(strat.text):
                code = m.group(1) + m.group(2)
                if code not in refs:
                    refs.append(code)
            source_objs = [code_map[r] for r in refs if r in code_map]
            if source_objs:
                strat.source_items.set(source_objs)
                linked += 1
            else:
                skipped += 1

        self.stdout.write(self.style.SUCCESS(
            f"«{BU_NAME}»: {len(code_map)} مورد SWOT شناسایی شد؛ {linked} راهبرد TOWS وصل شد، {skipped} بدون کد منبع بودند."
        ))
