def import_venture_swot(apps, schema_editor):
    BusinessUnit = apps.get_model("strategic", "BusinessUnit")
    SWOTItem = apps.get_model("strategic", "SWOTItem")
    TOWSStrategy = apps.get_model("strategic", "TOWSStrategy")

    candidates = list(BusinessUnit.objects.filter(name__icontains="واسطه"))
    if len(candidates) != 1:
        names = ", ".join(b.name for b in candidates) or "(هیچ‌کدام)"
        raise RuntimeError(
            "مهاجرت بند ۲۹۹ متوقف شد: کسب‌وکار «واسطه‌گری» به‌صورت "
            f"دقیق پیدا نشد (کاندیداهای یافت‌شده: {names}). لطفاً مطمئن "
            "شوید کسب‌وکاری با نامی شامل «واسطه» دقیقاً یکی توی سامانه "
            "وجود دارد، بعد دوباره «python manage.py migrate strategic» "
            "را اجرا کنید. تا وقتی این مشکل حل نشه، هیچ داده‌ای نوشته نمی‌شه."
        )
    bu = candidates[0]

    # قدم ۱: ساخت موارد SWOT (قوت/ضعف/فرصت/تهدید) و نگه‌داشتن نگاشت
    # کد <-> شیء ساخته‌شده، تا بعداً راهبردهای TOWS بتونن بهشون وصل بشن.
    code_to_item = {}
    category_map = {
        "strengths": "s",
        "weaknesses": "w",
        "opportunities": "o",
        "threats": "t",
    }
    created_swot = 0
    for key, category_code in category_map.items():
        for entry in DATA[key]:
            item, was_created = SWOTItem.objects.get_or_create(
                business_unit=bu,
                category=category_code,
                text=entry["text"],
                defaults={"impact": "med", "weight": 3},
            )
            code_to_item[entry["code"]] = item
            if was_created:
                created_swot += 1

    # قدم ۲: ساخت راهبردهای TOWS و وصل کردن‌شون به موارد SWOT مبنا
    # (کدهایی که داخل خود متن راهبرد، بین پرانتز آمده، مثل «S1,S2,O1,O2»).
    strategy_category_map = {"so": "so", "wo": "wo", "st": "st", "wt": "wt"}
    created_tows = 0
    for key, category_code in strategy_category_map.items():
        for order, entry in enumerate(DATA[key], start=1):
            strategy, was_created = TOWSStrategy.objects.get_or_create(
                business_unit=bu,
                category=category_code,
                text=entry["text"],
                defaults={"order": order},
            )
            if was_created:
                created_tows += 1
            first_part = entry["text"].split(":", 1)[0]
            ref_codes = re.findall(r"\b([SWOT]\d+)\b", first_part)
            matched_items = [code_to_item[c] for c in ref_codes if c in code_to_item]
            if matched_items:
                strategy.source_items.set(matched_items)

    print(
        f"\n[بند ۲۹۹] کسب‌وکار «{bu.name}» — "
        f"{created_swot} مورد SWOT جدید و {created_tows} راهبرد TOWS جدید "
        "ثبت شد (موارد تکراری رد شدند)."
    )


